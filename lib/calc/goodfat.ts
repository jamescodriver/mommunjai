// R15 — เป้าหมาย "ไขมันดี" (EPA+DHA) ต่อหมวดผู้ใช้ (pure, testable)
//
// 🔒 แหล่งเดียวของตัวเลขในไฟล์นี้คือ docs/GOOD-FAT-BY-CATEGORY-RESEARCH-BRIEF.md §0
//    (ต่อยอดจาก docs/GOOD-FAT-PREGNANCY-RESEARCH-BRIEF.md) — **ห้ามเพิ่ม/แก้ตัวเลขเอง**
//
// ⚠️ ข้อสรุปที่สำคัญที่สุดของบรีฟ (PRD R15 กล่องเตือน):
//    มีตัวเลขที่มีแหล่งอ้างอิงจริงแค่ **2 ค่า** ไม่ใช่ 5 ค่า
//      - prep · infertility · male → 250 มก./วัน (FAO/WHO 2010 ค่าผู้ใหญ่ทั่วไป)
//      - pregnant · lactating      → 300 มก./วัน (โดยเป็น DHA ≥ 200 มก.) — FAO/WHO 2010 Table 7.2
//    การสร้างเป้าแยก 5 หมวด = การแต่งตัวเลขขึ้นเอง ห้ามทำ
//    "สิ่งที่ต่างกันจริงตามหมวด" อยู่ที่ **เหตุผล** และ **ไขมันที่ต้องจำกัด** เท่านั้น → อยู่ในฟิลด์ copy ด้านล่าง
//
// 🔒 ข้อความบังคับ (บรีฟ §6.3): "ไขมันดีทั่วไป" (น้ำมันมะกอก/อะโวคาโด/ถั่ว) **ไม่ใช่แหล่ง DHA**
//    ต้องแยกเป็นคนละบล็อกเสมอ ห้ามเขียนรวมประโยคเดียว — โครงสร้างของ result จึงแยก
//    `dhaSources` ออกจาก `generalGoodFats` โดยตั้งใจ (หน้าจอ render คนละกล่อง)

export type GoodFatStage = "prep" | "infertility" | "pregnant" | "lactating" | "male";

export interface LimitFat {
  label: string;
  note: string;
}

export interface GoodFatResult {
  stage: GoodFatStage;
  /** เป้า EPA+DHA มก./วัน — มีได้แค่ 250 หรือ 300 เท่านั้น */
  epaDhaMgPerDay: 250 | 300;
  /** ขั้นต่ำเฉพาะ DHA — มีเฉพาะ pregnant/lactating (FAO/WHO Table 7.2) นอกนั้น null */
  dhaMinMgPerDay: number | null;
  targetLabel: string;
  /** องค์กร/ตารางต้นทางของ "ตัวเลข" (TC-15-05 ต้อง trace กลับได้) */
  source: string;
  /** เอกสารในโปรเจกต์ที่เก็บหลักฐานเต็ม */
  brief: string;
  /** เหตุผลของหมวดนี้ — จุดที่หมวดต่างกันจริง (ไม่ใช่ตัวเลข) */
  why: string;
  /** ความซื่อสัตย์เรื่องระดับหลักฐาน — กันการเคลมเกินจริงตาม legal-compliance.md */
  evidenceNote: string;
  limitFats: LimitFat[];
  /** ✅ ให้ DHA จริง (ปลาทะเล/สาหร่าย/อาหารเสริม) */
  dhaSources: string[];
  /** ❌ ไขมันดีทั่วไป — ดีต่อสุขภาพ แต่ไม่ให้ DHA */
  generalGoodFats: string[];
  notDhaWarning: string;
  /** ข้อควรระวังเฉพาะหมวด (ปรอท / อยู่ระหว่างรักษา / กินเจ) */
  extraCautions: string[];
}

const BRIEF = "docs/GOOD-FAT-BY-CATEGORY-RESEARCH-BRIEF.md §0";

const FAO_ADULT = "FAO/WHO 2010 — ค่า EPA+DHA ขั้นต่ำของผู้ใหญ่ทั่วไป (L-AMDR 250 มก./วัน)";
const FAO_PREG = "FAO/WHO 2010 Table 7.2 — \"Recommended NIV in pregnancy and lactation\" (EPA+DHA 300 มก./วัน โดยเป็น DHA 200 มก./วัน)";

// บรีฟ §6.2 — แหล่ง DHA จริง (ใช้ได้ทุกหมวด ต่างกันแค่ตัวเลขเป้า)
const DHA_SOURCES = [
  "ปลาทะเลไขมันสูง (แซลมอน · ซาร์ดีน · ปลาทู · แมคเคอเรลกลุ่มปรอทต่ำ) ~100–140 ก./มื้อ 2–3 มื้อ/สัปดาห์",
  "น้ำมันสาหร่าย (algal oil) — ทางเลือกสำหรับผู้กินเจ/มังสวิรัติ/แพ้ปลา",
  "อาหารเสริมน้ำมันปลาที่ระบุ DHA บนฉลาก (อ่านฉลากแม่นกว่าการประมาณจากอาหารสด)",
];

// บรีฟ §6.3 — "ไขมันดี" ที่คนทั่วไปเข้าใจ ดีต่อสุขภาพจริง แต่ **ไม่ให้ DHA**
const GENERAL_GOOD_FATS = [
  "น้ำมันมะกอก · น้ำมันคาโนลา",
  "อะโวคาโด",
  "ถั่วเปลือกแข็ง (อัลมอนด์ · แมคคาเดเมีย · คาชิว)",
  "เมล็ดแฟลกซ์ · เมล็ดเจีย · วอลนัท (เป็น ALA — ร่างกายแทบไม่แปลงเป็น DHA)",
];

// ⚠️ ข้อความทุกอันในไฟล์นี้ถูก render เป็น plain text ในหน้าจอ — ห้ามใส่ markdown (**bold**)
//    ไม่งั้นผู้ใช้จะเห็นเครื่องหมายดอกจันติดมาจริง ๆ (เจอตอน verify ในเบราว์เซอร์รอบแรก)
const NOT_DHA_WARNING =
  "ไขมันดีกลุ่มนี้ดีต่อสุขภาพ แต่ไม่ใช่แหล่ง DHA — กินน้ำมันมะกอก/อะโวคาโด/ถั่ว/เมล็ดแฟลกซ์มากแค่ไหนก็ไม่ได้ DHA เพิ่ม (FAO/WHO: ALA และ EPA ไม่ใช่สารตั้งต้นที่ร่างกายแปลงเป็น DHA ได้ดี) DHA ต้องมาจากปลาทะเล สาหร่าย หรืออาหารเสริมเท่านั้น";

const SATURATED_GENERAL: LimitFat = {
  label: "ไขมันอิ่มตัวส่วนเกิน",
  note: "ให้อยู่ไม่เกิน ~10% ของพลังงานที่ได้รับต่อวัน (ค่าเดียวกับผู้ใหญ่ทั่วไป)",
};
const TRANS_STRICT: LimitFat = {
  label: "ไขมันทรานส์ — เข้มกว่าคนทั่วไป",
  note: "FAO/WHO ระบุว่าช่วงนี้ควร \"ต่ำที่สุดเท่าที่ทำได้\" ไม่ใช่แค่ ≤1% ของพลังงาน",
};

const MERCURY_FISH =
  "เลือกปลากลุ่มปรอทต่ำ และเลี่ยงปลาปรอทสูง (ฉลาม · ปลาอินทรีราชา · ปลาดาบ · tilefish) · ทูน่าขาวไม่เกิน ~6 ออนซ์/สัปดาห์";

export function goodFatTarget(stage: GoodFatStage): GoodFatResult {
  const base = {
    stage,
    brief: BRIEF,
    dhaSources: DHA_SOURCES,
    generalGoodFats: GENERAL_GOOD_FATS,
    notDhaWarning: NOT_DHA_WARNING,
  };

  if (stage === "pregnant" || stage === "lactating") {
    const isPreg = stage === "pregnant";
    return {
      ...base,
      epaDhaMgPerDay: 300,
      dhaMinMgPerDay: 200,
      targetLabel: "EPA+DHA อย่างน้อย 300 มก./วัน (ในนั้นเป็น DHA อย่างน้อย 200 มก.)",
      source: FAO_PREG,
      why: isPreg
        ? "ช่วงตั้งครรภ์ลูกดึง DHA ไปใช้สร้างสมองและจอประสาทตา เข้มข้นที่สุดในไตรมาสที่ 3 — ร่างกายสะสม DHA แบบค่อยเป็นค่อยไป จึงควรได้รับสม่ำเสมอ ไม่ใช่เร่งทีเดียว"
        : "DHA ส่งผ่านน้ำนมถึงลูกได้จริง แม่ที่ให้นมล้วนถ่ายโอน DHA เฉลี่ยราว 110 มก./วัน — เป้า 300 มก./วันจึงครอบคลุมทั้งตัวแม่และส่วนที่ส่งให้ลูก",
      evidenceNote:
        "เป็นตัวเลขทางการจากตารางเดียวกันของ FAO/WHO ที่ครอบทั้งช่วงตั้งครรภ์และให้นม (ระดับหลักฐานสูงมาก) — เป็นคำแนะนำโภชนาการทั่วไป ไม่ใช่การรักษา",
      limitFats: [TRANS_STRICT, SATURATED_GENERAL],
      extraCautions: isPreg
        ? [MERCURY_FISH]
        : [
            MERCURY_FISH,
            "ถ้ากินเจ/มังสวิรัติเข้มงวด ควรพิจารณาน้ำมันสาหร่ายจริงจัง — งานวิจัยพบว่าการเติมน้ำมันพืช (ALA) ไม่ได้ทำให้ DHA ในน้ำนมเพิ่มขึ้น",
          ],
    };
  }

  if (stage === "male") {
    return {
      ...base,
      epaDhaMgPerDay: 250,
      dhaMinMgPerDay: null,
      targetLabel: "EPA+DHA อย่างน้อย 250 มก./วัน (ค่าผู้ใหญ่ทั่วไป)",
      source: FAO_ADULT,
      why: "ใช้ค่าผู้ใหญ่ทั่วไปในกรอบ \"สุขภาพโดยรวมที่ดี\" — ฝั่งที่หลักฐานหนักแน่นกว่าสำหรับผู้ชายคือการ *ลด* ไขมันทรานส์และไขมันอิ่มตัวส่วนเกิน มากกว่าการ *เพิ่ม* โอเมกา-3",
      evidenceNote:
        "แนวทาง AUA/ASRM 2024 ระบุว่าประโยชน์ของอาหารเสริมต่อภาวะมีบุตรยากในเพศชาย \"ยังน่าสงสัยทางคลินิก\" และยังไม่มีข้อมูลอัตราการตั้งครรภ์/คลอดมีชีพ — ข้อมูลนี้จึงเป็นโภชนาการเพื่อสุขภาพโดยรวม ไม่ใช่การรักษา",
      limitFats: [
        {
          label: "ไขมันทรานส์",
          note: "งานวิจัยเชิงสังเกตในชายสุขภาพดีพบว่ากลุ่มที่กินไขมันทรานส์มากมีปริมาณอสุจิรวมต่ำกว่า — เป็นการศึกษาแบบสังเกต ยังสรุปเหตุ-ผลไม่ได้ แต่หลีกเลี่ยงไว้ดีกว่า",
        },
        {
          label: "ไขมันอิ่มตัวส่วนเกิน",
          note: "งานวิจัยเชิงสังเกตพบความสัมพันธ์กับความเข้มข้นอสุจิที่ต่ำกว่า — ให้อยู่ไม่เกิน ~10% ของพลังงานต่อวัน",
        },
      ],
      extraCautions: [MERCURY_FISH],
    };
  }

  // prep + infertility — ตัวเลขเดียวกัน ต่างกันที่ "โทนเสียง" และข้อควรระวัง (บรีฟ §3.3)
  const isInfertility = stage === "infertility";
  return {
    ...base,
    epaDhaMgPerDay: 250,
    dhaMinMgPerDay: null,
    targetLabel: "EPA+DHA อย่างน้อย 250 มก./วัน (ค่าผู้ใหญ่ทั่วไป)",
    source: FAO_ADULT,
    why: isInfertility
      ? // 🔒 ASRM 2022: "insufficient evidence that a specific diet or intake of particular
        // macronutrients can improve natural fertility" → ห้ามเขียนว่าไขมันดีช่วยให้ท้องง่ายขึ้น
        // กรอบที่ใช้ได้คือ "โภชนาการพื้นฐานที่ดี" เท่านั้น
        "เป็นเป้าโภชนาการพื้นฐานสำหรับผู้ใหญ่ที่ควรได้รับพออยู่แล้ว เพื่อสุขภาพโดยรวมและความพร้อมของร่างกาย"
      : "ร่างกายสะสม DHA แบบค่อยเป็นค่อยไปจนอิ่มตัว ไม่ใช่เติมวันนี้แล้วพรุ่งนี้พอ — การเริ่มสะสมตั้งแต่ก่อนตั้งครรภ์ทำให้พร้อมเมื่อถึงไตรมาสที่ 3 ที่ลูกต้องการ DHA มากที่สุด",
    evidenceNote: isInfertility
      ? "ยังไม่มีองค์กรทางการแพทย์ใดยืนยันว่าโอเมกา-3 หรือสารอาหารชนิดใดช่วยเพิ่มโอกาสตั้งครรภ์ตามธรรมชาติ (ASRM 2022 ระบุว่าหลักฐานยังไม่เพียงพอ และ ESHRE 2023 ไม่ได้กล่าวถึงโอเมกา-3 เลย) — ตัวเลขนี้จึงเป็นค่าโภชนาการทั่วไป ไม่ใช่คำแนะนำเพื่อการเจริญพันธุ์"
      : "ตัวเลข 250 มก./วัน เป็นค่าผู้ใหญ่ทั่วไป ไม่ใช่ตัวเลข \"เพื่อให้ตั้งครรภ์ง่ายขึ้น\" — ยังไม่มีองค์กรใดกำหนดเป้าไขมันเพื่อการเจริญพันธุ์โดยตรง",
    limitFats: [
      {
        label: "ไขมันทรานส์",
        note: "มีงานวิจัยขนาดใหญ่แบบสังเกตพบความสัมพันธ์กับภาวะไข่ไม่ตก — ยังพิสูจน์ไม่ได้ว่าเป็นสาเหตุ แต่หลีกเลี่ยงไว้ดีกว่า (เบเกอรี่ · ของทอดซ้ำ · ครีมเทียม)",
      },
      SATURATED_GENERAL,
    ],
    extraCautions: isInfertility
      ? [
          MERCURY_FISH + " — มีรายงานว่าระดับปรอทในเลือดสูงสัมพันธ์กับภาวะมีบุตรยาก",
          "ถ้ากำลังอยู่ระหว่างการรักษา (IUI/IVF/ICSI) ให้ปรึกษาแพทย์ที่ดูแลก่อนเริ่มอาหารเสริมทุกชนิด",
        ]
      : [MERCURY_FISH + " — มีรายงานว่าระดับปรอทในเลือดสูงสัมพันธ์กับภาวะมีบุตรยาก"],
  };
}
