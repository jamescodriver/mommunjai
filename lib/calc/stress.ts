/**
 * คำนวณผล ST-5 จากคำตอบ 5 ข้อ
 * @param answers อาร์เรย์ยาว 5 ค่า 0–3 · ถ้ายังตอบไม่ครบ/ค่าไม่ถูกต้อง คืน null (ไม่ throw)
 */
export function scoreSt5(answers: (number | null)[]): StressResult | null {
  if (!Array.isArray(answers) || answers.length !== ST5_QUESTIONS.length) return null;
  let score = 0;
  for (const a of answers) {
    if (a === null || !Number.isInteger(a) || a < 0 || a > 3) return null;
    score += a;
  }
  const b = BANDS.find((x) => score <= x.max) ?? BANDS[BANDS.length - 1];
  // มติต้น 31/7 (PRD R3 §R14): คะแนน 8 ขึ้นไป → ขึ้นช่องทางช่วยเหลือก่อน และกรอบสินค้า
  // ต้องเปลี่ยนหัวข้อเป็น "ตัวช่วย" เพื่อไม่ให้เป็นการเสนอขายกับคนที่กำลังเปราะบาง
  const needsSupport = b.band === "high" || b.band === "severe";
  return {
    score,
    band: b.band,
    bandLabel: b.label,
    color: b.color,
    advice: b.advice,
    showHelpline: needsSupport,
    productsAsAid: needsSupport,
  };
}
