export function buildPregnancyKnowledge(input: { gestationalWeeks?: number }): PregnancyKnowledge {
  const weeks = typeof input.gestationalWeeks === "number" && Number.isFinite(input.gestationalWeeks)
    ? input.gestationalWeeks
    : undefined;
  const trimester = trimesterFromWeeks(weeks);

  // TC-10-03 — น้ำหัวปลีเพิ่มเมื่ออายุครรภ์ 16 สัปดาห์ขึ้นไปเท่านั้น
  // ไม่กรอกอายุครรภ์ = ไม่เพิ่ม (ห้ามเดาแทนผู้ใช้)
  const ids = [...PREGNANCY_PRODUCT_IDS];
  if (weeks !== undefined && weeks >= BANANA_FLOWER_MIN_WEEKS) ids.push("bananaflower");

  // 🔒 ต้องไหลผ่าน Safety Matrix เหมือนทุกเส้นทางที่แนะนำสินค้า
  const allowed = productsForStage("pregnant", ids);

  const notes: Record<string, string> = {
    // บรีฟ §12.2 — นมแพะวางเป็น "เครื่องดื่มบำรุงสำหรับคุณแม่" เท่านั้น
    goatmilk: "เครื่องดื่มบำรุงสำหรับคุณแม่ ใช้ชง Ferty ได้",
    // บรีฟ §13 ข้อ 1 — ทีมยังไม่ได้ให้เหตุผลว่าทำไมน้ำหัวปลีถึงอยู่ในชุดตั้งครรภ์
    // จึงห้ามเขียนสรรพคุณใด ๆ ให้เอง (จะกลายเป็นเคลมลอย)
    bananaflower: `ทีม Baby & Mom กำหนดให้เริ่มแนะนำเมื่ออายุครรภ์ ${BANANA_FLOWER_MIN_WEEKS} สัปดาห์ขึ้นไป เหตุผลเชิงโภชนาการยังรอทีมยืนยัน เราจึงยังไม่ระบุสรรพคุณใด ๆ ไว้ที่นี่`,
  };

  return {
    gestationalWeeks: weeks,
    trimester,
    trimesterNote: trimester
      ? `อายุครรภ์ ${weeks} สัปดาห์ อยู่ใน${TRIMESTER_DEVELOPMENT[trimester - 1].label}`
      : "ยังไม่ได้กรอกอายุครรภ์ เราจึงยังไม่ระบุไตรมาสให้ (ไม่เดาตัวเลขแทนคุณ) ด้านล่างแสดงข้อมูลครบทุกไตรมาส",
    development: trimester ? TRIMESTER_DEVELOPMENT[trimester - 1] : null,
    allDevelopment: TRIMESTER_DEVELOPMENT,
    developmentSource: DEVELOPMENT_SOURCE,
    nutrients: {
      items: KEY_NUTRIENTS,
      source: NUTRIENT_SOURCE,
      noTrimesterNumbers: NUTRIENT_NO_TRIMESTER_NUMBERS,
      focus: trimester ? NUTRIENT_FOCUS[trimester - 1] : null,
      allFocus: NUTRIENT_FOCUS,
      calciumMisreadWarning: CALCIUM_MISREAD_WARNING,
      supplementWarnings: SUPPLEMENT_WARNINGS,
    },
    kick: {
      modes: KICK_MODES,
      alwaysVisibleSafety: KICK_ALWAYS_VISIBLE_SAFETY,
      noVerdictRule: KICK_NO_VERDICT_RULE,
      gestationNote: KICK_GESTATION_NOTE,
      evidenceNote: KICK_EVIDENCE_NOTE,
    },
    danger: {
      signs: DANGER_SIGNS,
      cta: DANGER_CTA,
      source: DANGER_SOURCE,
      timeframeNote: DANGER_TIMEFRAME_NOTE,
    },
    products: allowed.map((p) => ({ product: p, note: notes[p.id] })),
    fbMenuUrl: PREGNANCY_FB_MENU_URL,
    brief: BRIEF,
  };
}

