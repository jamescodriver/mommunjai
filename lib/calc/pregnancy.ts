/** ขอบเขตไตรมาสตาม ACOG คือ 13+6 / 27+6 (ไม่ใช่ 12/26 หรือ 13/27)
 *  → เมื่อเก็บอายุครรภ์เป็น "สัปดาห์" จำนวนเต็ม (R9): 1–13 = ไตรมาส 1 · 14–27 = 2 · 28+ = 3
 *  คืน null เมื่อไม่ได้กรอก/ค่าใช้ไม่ได้ — **ห้ามเดาไตรมาสให้** (บรีฟ §1.1 กล่องเตือน) */
export function trimesterFromWeeks(weeks?: number | null): Trimester | null {
  if (typeof weeks !== "number" || !Number.isFinite(weeks)) return null;
  if (weeks < 1) return null;
  if (weeks <= 13) return 1;
  if (weeks <= 27) return 2;
  return 3;
}

